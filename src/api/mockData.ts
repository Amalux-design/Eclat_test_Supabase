import type { WorkLog } from "../types";
import { generateId } from "../utils/id";
import { toISODate } from "../utils/format";

function daysFromToday(offset: number): string {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return toISODate(d);
}

const NOW = new Date().toISOString();

function log(partial: Partial<WorkLog> & Pick<WorkLog, "date" | "clientName" | "work" | "amount">): WorkLog {
  const status = partial.date <= toISODate(new Date()) ? "WORKED" : "RESERVED";
  return {
    id: generateId(),
    clientPhone: "",
    altPhone: "",
    eventType: "",
    location: "",
    bridesmaids: 0,
    qty: 1,
    price: partial.amount,
    paymentStatus: "PENDING",
    status,
    own: true,
    referrerName: "",
    startTime: "",
    endTime: "",
    notes: "",
    privateNotes: "",
    paidAmount: 0,
    createdAt: NOW,
    updatedAt: NOW,
    ...partial,
  };
}


// Converts the old Google Sheet (WORK_LOGS tab, downloaded as CSV) into SQL
// you can paste into Supabase → SQL Editor. Nothing is uploaded anywhere.
//
//   node scripts/sheet-to-sql.mjs path/to/WORK_LOGS.csv > supabase/import.sql
//
// Phone numbers are cleaned to plain 10-digit Indian mobiles; anything that
// doesn't reduce cleanly is kept exactly as it was.
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";

const file = process.argv[2];
if (!file) {
  console.error("Usage: node scripts/sheet-to-sql.mjs WORK_LOGS.csv > supabase/import.sql");
  process.exit(1);
}

/** RFC 4180 CSV parser (handles quotes, commas and newlines inside cells). */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(cell);
      cell = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = "";
    } else cell += c;
  }
  if (cell || row.length) {
    row.push(cell);
    rows.push(row);
  }
  return rows.filter((r) => r.some((v) => v.trim() !== ""));
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const q = (v) => `'${String(v ?? "").replace(/'/g, "''")}'`;
const num = (v, d = 0) => (Number.isFinite(Number(v)) && String(v).trim() !== "" ? Number(v) : d);

function phone(raw) {
  const typed = String(raw ?? "").trim();
  if (!typed) return "";
  let d = typed.replace(/\D/g, "");
  if (d.length === 12 && d.startsWith("91")) d = d.slice(2);
  else if (d.length === 11 && d.startsWith("0")) d = d.slice(1);
  return d.length === 10 ? d : typed;
}

function isoDate(raw) {
  const s = String(raw ?? "").trim();
  if (/^\d{4}-\d{2}-\d{2}/.test(s)) return s.slice(0, 10);
  const m = s.match(/^(\d{1,2})[/.-](\d{1,2})[/.-](\d{4})$/); // dd/mm/yyyy
  if (m) return `${m[3]}-${m[2].padStart(2, "0")}-${m[1].padStart(2, "0")}`;
  return null;
}

function time(raw) {
  const s = String(raw ?? "").trim();
  const m = s.match(/^(\d{1,2}):(\d{2})/);
  return m ? `${m[1].padStart(2, "0")}:${m[2]}` : "";
}

const [header, ...data] = parseCsv(readFileSync(file, "utf8").replace(/^﻿/, ""));
const col = Object.fromEntries(header.map((h, i) => [h.trim(), i]));
const get = (r, k) => (col[k] === undefined ? "" : r[col[k]] ?? "");

const out = ["-- Generated by scripts/sheet-to-sql.mjs. Run once in Supabase → SQL Editor.", "begin;"];
let skipped = 0;
for (const r of data) {
  const date = isoDate(get(r, "date"));
  if (!date) {
    skipped++;
    continue;
  }
  const id = UUID.test(get(r, "id").trim()) ? get(r, "id").trim() : randomUUID();
  const status = get(r, "status").trim().toUpperCase() === "WORKED" ? "WORKED" : "RESERVED";
  const amount = num(get(r, "amount"));
  const paidStatus = get(r, "paymentStatus").trim().toUpperCase() === "PAID" ? "PAID" : "PENDING";
  const own = !/^false$/i.test(get(r, "own").trim());
  out.push(
    `insert into public.bookings (id, date, client_name, work, event_type, location, bridesmaids, status, start_time, end_time, notes) values (` +
      [q(id), q(date), q(get(r, "clientName")), q(get(r, "work")), q(get(r, "eventType")), q(get(r, "location")),
        num(get(r, "bridesmaids")), q(status), q(time(get(r, "startTime"))), q(time(get(r, "endTime"))), q(get(r, "notes"))].join(", ") +
      `) on conflict (id) do nothing;`
  );
  out.push(
    `insert into public.booking_private (booking_id, client_phone, alt_phone, qty, price, amount, paid_amount, payment_status, own, referrer_name, private_notes) values (` +
      [q(id), q(phone(get(r, "clientPhone"))), q(phone(get(r, "altPhone"))), num(get(r, "qty"), 1), num(get(r, "price"), amount),
        amount, paidStatus === "PAID" ? amount : num(get(r, "paidAmount")), q(paidStatus), own, q(get(r, "referrerName")),
        q(get(r, "privateNotes"))].join(", ") +
      `) on conflict (booking_id) do nothing;`
  );
}
out.push("commit;");
console.log(out.join("\n"));
console.error(`Converted ${data.length - skipped} bookings${skipped ? `, skipped ${skipped} rows without a valid date` : ""}.`);
